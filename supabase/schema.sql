create or replace function public.import_inventory_snapshot(
  p_snapshot_date date,
  p_source_file_name text,
  p_source_file_hash text,
  p_rows jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user uuid := (select auth.uid());
  v_snapshot_id uuid;
  v_previous_id uuid;
  v_row_count integer;
  v_changes integer := 0;
begin
  if v_user is null then raise exception 'AUTH_REQUIRED'; end if;
  if not (select public.is_operator_or_admin()) then raise exception 'ROLE_NOT_ALLOWED'; end if;
  if jsonb_typeof(p_rows) <> 'array' then raise exception 'ROWS_MUST_BE_ARRAY'; end if;
  if jsonb_array_length(p_rows) = 0 then raise exception 'ROWS_EMPTY'; end if;
  if length(coalesce(p_source_file_hash,'')) < 32 then raise exception 'INVALID_FILE_HASH'; end if;
  if exists(select 1 from public.inventory_snapshots where snapshot_date = p_snapshot_date) then raise exception 'SNAPSHOT_DATE_ALREADY_EXISTS'; end if;
  if exists(select 1 from public.inventory_snapshots where source_file_hash = p_source_file_hash) then raise exception 'DUPLICATE_FILE'; end if;

  select id into v_previous_id from public.inventory_snapshots
  where snapshot_date < p_snapshot_date order by snapshot_date desc limit 1;

  insert into public.inventory_snapshots(snapshot_date,source_file_name,source_file_hash,row_count,imported_by)
  values(p_snapshot_date,p_source_file_name,p_source_file_hash,jsonb_array_length(p_rows),v_user)
  returning id into v_snapshot_id;

  insert into public.inventory_snapshot_rows(
    snapshot_id,part_no,material_name,rating,warehouse,storage_bin,quantity,safety_stock,received_date,last_used_date
  )
  select v_snapshot_id,x.part_no,x.material_name,coalesce(x.rating,''),coalesce(x.warehouse,''),coalesce(x.storage_bin,''),
         coalesce(x.quantity,0),coalesce(x.safety_stock,0),x.received_date,x.last_used_date
  from jsonb_to_recordset(p_rows) as x(
    part_no text, material_name text, rating text, warehouse text, storage_bin text,
    quantity numeric, safety_stock numeric, received_date date, last_used_date date
  )
  where nullif(trim(x.part_no),'') is not null and nullif(trim(coalesce(x.warehouse,'')),'') is not null;

  select count(*) into v_row_count from public.inventory_snapshot_rows where snapshot_id=v_snapshot_id;
  if v_row_count = 0 then raise exception 'NO_VALID_ROWS'; end if;
  update public.inventory_snapshots set row_count=v_row_count where id=v_snapshot_id;

  insert into public.materials(part_no,material_name,unit)
  select distinct part_no,max(material_name),'' from public.inventory_snapshot_rows
  where snapshot_id=v_snapshot_id group by part_no
  on conflict(part_no) do update set material_name=excluded.material_name;

  if v_previous_id is not null then
    insert into public.inventory_changes(
      from_snapshot_id,to_snapshot_id,part_no,material_name,rating,warehouse,
      previous_quantity,current_quantity,quantity_delta,change_type,safety_stock
    )
    with prev as (
      select part_no,rating,warehouse,sum(quantity) quantity
      from public.inventory_snapshot_rows where snapshot_id=v_previous_id
      group by part_no,rating,warehouse
    ), curr as (
      select part_no,max(material_name) material_name,rating,warehouse,sum(quantity) quantity,max(safety_stock) safety_stock
      from public.inventory_snapshot_rows where snapshot_id=v_snapshot_id
      group by part_no,rating,warehouse
    ), merged as (
      select coalesce(c.part_no,p.part_no) part_no,coalesce(c.material_name,'') material_name,
             coalesce(c.rating,p.rating,'') rating,coalesce(c.warehouse,p.warehouse,'') warehouse,
             coalesce(p.quantity,0) previous_quantity,coalesce(c.quantity,0) current_quantity,
             coalesce(c.safety_stock,0) safety_stock
      from prev p full outer join curr c
      on p.part_no=c.part_no and p.rating=c.rating and p.warehouse=c.warehouse
    )
    select v_previous_id,v_snapshot_id,part_no,material_name,rating,warehouse,
           previous_quantity,current_quantity,current_quantity-previous_quantity,
           case when previous_quantity=0 and current_quantity<>0 then 'new'
                when previous_quantity<>0 and current_quantity=0 then 'disappeared'
                when current_quantity>previous_quantity then 'increase'
                when current_quantity<previous_quantity then 'decrease' end,
           safety_stock
    from merged where current_quantity<>previous_quantity;
    select count(*) into v_changes from public.inventory_changes where to_snapshot_id=v_snapshot_id;
  end if;

  insert into public.import_audit(snapshot_id,action,source_file_name,source_file_hash,row_count,success,operator_id)
  values(v_snapshot_id,'IMPORT',p_source_file_name,p_source_file_hash,v_row_count,true,v_user);

  return jsonb_build_object('snapshot_id',v_snapshot_id,'row_count',v_row_count,'change_count',v_changes,'previous_snapshot_id',v_previous_id);
exception when others then
  insert into public.import_audit(action,source_file_name,source_file_hash,success,error_message,operator_id)
  values('IMPORT',p_source_file_name,p_source_file_hash,false,sqlerrm,v_user);
  raise;
end;
$$;

revoke all on function public.import_inventory_snapshot(date,text,text,jsonb) from public,anon;
grant execute on function public.import_inventory_snapshot(date,text,text,jsonb) to authenticated;

create or replace function public.agent_heartbeat(
  p_machine_name text,
  p_status text default 'WAITING',
  p_last_file text default null,
  p_last_imported_date date default null,
  p_last_imported_hash text default null,
  p_last_scan timestamptz default now(),
  p_last_error text default null
)
returns jsonb
language plpgsql
security definer
set search_path=''
as $$
declare v_user uuid := (select auth.uid());
begin
  if v_user is null then raise exception 'AUTH_REQUIRED'; end if;
  if not (select public.is_operator_or_admin()) then raise exception 'ROLE_NOT_ALLOWED'; end if;
  insert into public.agent_status(machine_name,status,last_file,last_imported_date,last_imported_hash,last_scan_at,last_error,updated_by)
  values(p_machine_name,coalesce(p_status,'WAITING'),p_last_file,p_last_imported_date,p_last_imported_hash,coalesce(p_last_scan,now()),p_last_error,v_user)
  on conflict(machine_name) do update set status=excluded.status,last_file=excluded.last_file,
    last_imported_date=coalesce(excluded.last_imported_date,public.agent_status.last_imported_date),
    last_imported_hash=coalesce(excluded.last_imported_hash,public.agent_status.last_imported_hash),
    last_scan_at=excluded.last_scan_at,last_error=excluded.last_error,updated_by=excluded.updated_by;
  return jsonb_build_object('ok',true,'machine_name',p_machine_name);
end;
$$;

revoke all on function public.agent_heartbeat(text,text,text,date,text,timestamptz,text) from public,anon;
grant execute on function public.agent_heartbeat(text,text,text,date,text,timestamptz,text) to authenticated;

