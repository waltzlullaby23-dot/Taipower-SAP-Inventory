-- MaterialMind V2
-- Central inventory database + transactional import + Windows Auto-Sync Agent
-- Run this whole file in Supabase SQL Editor.

create extension if not exists pgcrypto;

do $$ begin
  create type public.app_role as enum ('admin','operator','viewer');
exception when duplicate_object then null; end $$;

create table if not exists public.profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  display_name text,
  role public.app_role not null default 'viewer',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.materials (
  part_no text primary key,
  material_name text,
  material_category text,
  management_code text,
  unit text,
  old_part_no text,
  default_safety_stock numeric not null default 0,
  updated_at timestamptz not null default now()
);

create table if not exists public.inventory_snapshots (
  id uuid primary key default gen_random_uuid(),
  snapshot_date date not null unique,
  source_file_name text not null,
  source_file_hash text not null,
  row_count integer not null default 0,
  imported_by uuid not null references auth.users(id),
  imported_at timestamptz not null default now()
);

create unique index if not exists inventory_snapshots_hash_uq
  on public.inventory_snapshots(source_file_hash);

create table if not exists public.inventory_snapshot_rows (
  snapshot_id uuid not null references public.inventory_snapshots(id) on delete cascade,
  part_no text not null,
  material_name text,
  rating text not null default '',
  warehouse text not null default '',
  storage_bin text not null default '',
  quantity numeric not null default 0,
  safety_stock numeric not null default 0,
  received_date date,
  last_used_date date,
  primary key (snapshot_id, part_no, rating, warehouse, storage_bin)
);

create index if not exists snapshot_rows_lookup_idx
  on public.inventory_snapshot_rows(snapshot_id, part_no, rating, warehouse);

create table if not exists public.inventory_changes (
  id bigint generated by default as identity primary key,
  from_snapshot_id uuid not null references public.inventory_snapshots(id) on delete cascade,
  to_snapshot_id uuid not null references public.inventory_snapshots(id) on delete cascade,
  part_no text not null,
  material_name text,
  rating text not null default '',
  warehouse text not null default '',
  previous_quantity numeric not null default 0,
  current_quantity numeric not null default 0,
  quantity_delta numeric not null default 0,
  change_type text not null check (change_type in ('increase','decrease','new','disappeared')),
  safety_stock numeric not null default 0,
  created_at timestamptz not null default now(),
  unique(to_snapshot_id, part_no, rating, warehouse)
);

create index if not exists inventory_changes_to_idx
  on public.inventory_changes(to_snapshot_id, change_type);

create table if not exists public.import_audit (
  id bigint generated by default as identity primary key,
  snapshot_id uuid references public.inventory_snapshots(id) on delete set null,
  action text not null,
  source_file_name text,
  source_file_hash text,
  row_count integer,
  success boolean not null,
  error_message text,
  operator_id uuid references auth.users(id),
  created_at timestamptz not null default now()
);

create index if not exists import_audit_created_idx on public.import_audit(created_at desc);

-- Windows Agent heartbeat / health status.
create table if not exists public.agent_status (
  machine_name text primary key,
  status text not null default 'WAITING',
  last_file text,
  last_imported_date date,
  last_imported_hash text,
  last_scan_at timestamptz,
  last_error text,
  updated_at timestamptz not null default now(),
  updated_by uuid references auth.users(id)
);

create index if not exists agent_status_updated_idx on public.agent_status(updated_at desc);

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles(user_id, display_name)
  values (new.id, coalesce(new.raw_user_meta_data ->> 'full_name', new.email));
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute procedure public.handle_new_user();

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists(select 1 from public.profiles where user_id = (select auth.uid()) and role = 'admin');
$$;

create or replace function public.is_operator_or_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists(
    select 1 from public.profiles
    where user_id = (select auth.uid()) and role in ('admin','operator')
  );
$$;

revoke all on function public.is_admin() from public;
revoke all on function public.is_operator_or_admin() from public;
grant execute on function public.is_admin() to authenticated;
grant execute on function public.is_operator_or_admin() to authenticated;

create or replace function public.touch_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

